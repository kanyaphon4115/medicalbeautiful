import test from 'node:test';
import assert from 'node:assert/strict';
import {browserAdapter,requestData,codeFields} from '../helpers/guest-dom.mjs';

test('demo email links, replacement, payment and account setup work without network calls',async()=>{
 const b=browserAdapter();b.host.dataset.notificationDemo='true';
 // Even a stale live endpoint and old opt-in URL must never send real mail in this mode.
 b.host.dataset.realRequestStore='/guest-requests';
 let calls=0;globalThis.fetch=()=>{calls++;throw Error('Network disabled for this demo');};
 const {journey}=await import('../../resources/js/guest-journey.js');
 location.hash='#journey/new?email=real';
 await b.submit('request',{...requestData,goals:'SECRET-GOAL',medical_information:'SECRET-MEDICAL'});
 const r=journey.state.requests[0],n=journey.state.notifications[0];
 assert.equal(journey.state.notifications.length,2);
 assert.match(b.host.innerHTML,/Hospital response notifications/);
 assert.doesNotMatch(b.host.innerHTML,/Resend access link/);
 b.go('notifications');assert.match(b.host.innerHTML,/Demo Email Notifications/);
 b.go('notification-email',{token:n.id});
 assert.match(b.host.innerHTML,/View Quotation/);
 assert.match(b.host.innerHTML,new RegExp(r.id));
 assert.doesNotMatch(b.host.innerHTML,/SECRET-GOAL|SECRET-MEDICAL|<img/);
 r.accessUntil=0;b.go('guest-link',r,n.linkToken);
 assert.match(b.host.innerHTML,/Select a Hospital/);
 assert.equal(journey.state.accounts.length,0);
 await b.click('respond',r.quotes[0].hospital);
 assert.equal(journey.state.notifications.length,2);
 r.guestLinks.find(link=>link.token===n.linkToken).expires=Date.now()-1;
 b.go('guest-link',r,n.linkToken);
 assert.match(b.host.innerHTML,/invalid or has expired/);
 assert.match(b.host.innerHTML,/data-form="replacement"/);
 await b.submit('replacement',{reference:r.id,email:'unknown@example.test'});
 const generic=b.host.innerHTML;
 await b.submit('replacement',{reference:r.id,email:r.email});
 assert.equal(b.host.innerHTML,generic);
 const replacement=journey.state.notifications.at(-1);
 b.go('guest-link',r,replacement.linkToken);
 b.go('checkout',r,r.quotes[0].id);
 assert.match(b.host.innerHTML,/NOT SCANNABLE/);assert.equal(r.otp,undefined);
 await b.click('payment-claim');assert.equal(r.booking,null);
 await b.click('provider-confirm');assert.match(r.otp.code,/^\d{6}$/);
 b.go('verify',r);await b.submit('verify',codeFields(r.otp.code),r);
 assert.match(b.host.innerHTML,/Create Your Account/);
 await b.submit('account',{username:'demo.guest',password:'OnlyADemo123!',confirm:'OnlyADemo123!',terms:'1'},r);
 assert.equal(journey.state.current,r.email);
 assert.match(b.host.innerHTML,/Quotation Notifications/);
 await b.click('email-alerts');assert.equal(journey.state.accounts[0].emailAlerts,false);
 // A general response is visible even before any quotation; alerts can be off.
 location.hash='#journey/new';
 await b.submit('request',{...requestData,wait_for_quotes:'1'});
 const second=journey.state.requests.at(-1),before=journey.state.notifications.length;
 await b.click('demo-reply',second.hospitals[0]);
 assert.match(b.host.innerHTML,/Hospital Responses/);
 assert.match(b.host.innerHTML,/acknowledged your request/);
 assert.doesNotMatch(b.host.innerHTML,/No hospital has responded yet/);
 assert.equal(journey.state.notifications.length,before+1);
 assert.equal(journey.state.notifications.at(-1).emailSent,false);
 await b.click('demo-reply',second.hospitals[0]);
 assert.equal(journey.state.notifications.length,before+1);
 b.go('dashboard');assert.match(b.host.innerHTML,new RegExp(second.id));
 assert.equal(calls,0);
 b.go('home');
});
